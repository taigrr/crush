// Package devicescope derives the device route allow-list from the
// x-crush-scope annotations in the /v1 OpenAPI document
// (docs/specs/MOBILE_DEVICE_BRIDGE.md, Permissions).
package devicescope

import (
	"encoding/json"
	"errors"
	"fmt"
	"maps"
	"net/http"
	"slices"
	"strings"
)

// Extension is the OpenAPI operation extension naming a route's scope.
const Extension = "x-crush-scope"

// Device scopes (docs/specs/MOBILE_PAIRING.md, Permissions).
const (
	SessionsRead      = "sessions:read"
	SessionsPrompt    = "sessions:prompt"
	PermissionsAnswer = "permissions:answer"
	PermissionsAlways = "permissions:always"
	ConfigModel       = "config:model"
	SessionsMove      = "sessions:move"
	Shell             = "shell"
	DevicesApprove    = "devices:approve"
	ClusterApprove    = "cluster:approve"
	// Never marks a route no device may call, whatever its scopes.
	Never = "never"
)

// Known lists every value an x-crush-scope annotation may take.
var Known = []string{
	SessionsRead, SessionsPrompt, PermissionsAnswer, PermissionsAlways,
	ConfigModel, SessionsMove, Shell, DevicesApprove, ClusterApprove, Never,
}

// methods are the OpenAPI operation keys that are HTTP methods.
var methods = []string{
	http.MethodGet, http.MethodPost, http.MethodPut, http.MethodPatch,
	http.MethodDelete, http.MethodHead, http.MethodOptions,
}

// ErrUnannotated reports operations without a valid x-crush-scope.
var ErrUnannotated = errors.New("operations without a valid " + Extension)

// FromSwagger returns "METHOD /base/path" → scope for every operation in
// an OpenAPI 2 document. It fails if any operation lacks the annotation
// or names an unknown scope, so a new route is never silently reachable
// (or silently unreachable) by devices.
func FromSwagger(doc []byte) (map[string]string, error) {
	var spec struct {
		BasePath string                                `json:"basePath"`
		Paths    map[string]map[string]json.RawMessage `json:"paths"`
	}
	if err := json.Unmarshal(doc, &spec); err != nil {
		return nil, fmt.Errorf("parse swagger: %w", err)
	}
	if len(spec.Paths) == 0 {
		return nil, errors.New("swagger has no paths")
	}
	base := strings.TrimSuffix(spec.BasePath, "/")
	out := map[string]string{}
	var bad []string
	for p, ops := range spec.Paths {
		for key, raw := range ops {
			method := strings.ToUpper(key)
			if !slices.Contains(methods, method) {
				continue
			}
			var op map[string]json.RawMessage
			if err := json.Unmarshal(raw, &op); err != nil {
				return nil, fmt.Errorf("parse %s %s: %w", method, p, err)
			}
			route := method + " " + base + p
			var scope string
			if v, ok := op[Extension]; !ok || json.Unmarshal(v, &scope) != nil || !slices.Contains(Known, scope) {
				bad = append(bad, route)
				continue
			}
			out[route] = scope
		}
	}
	if len(bad) > 0 {
		slices.Sort(bad)
		return nil, fmt.Errorf("%w: %s", ErrUnannotated, strings.Join(bad, ", "))
	}
	return out, nil
}

// Source renders routes as the Go source of the generated table.
func Source(pkg string, routes map[string]string) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by gendevicescopes from internal/swagger; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("// deviceRoutes maps every documented /v1 route to the device scope it\n")
	b.WriteString("// needs (\"never\": unreachable by devices). Undocumented routes are\n")
	b.WriteString("// absent and therefore denied.\n")
	b.WriteString("var deviceRoutes = map[string]string{\n")
	for _, k := range slices.Sorted(maps.Keys(routes)) {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, routes[k])
	}
	b.WriteString("}\n")
	return []byte(b.String())
}
